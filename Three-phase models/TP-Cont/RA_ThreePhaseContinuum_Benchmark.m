function benchmark = RA_ThreePhaseContinuum_Benchmark(caseData)
    % RA_THREEPHASECONTINUUM_BENCHMARK Verify continuum-model identities.
    %
    % PURPOSE
    %   Run independent checks for both global gas-transport closures:
    %
    %   1. Zero-relative-flux closure:
    %          q_relative = 0
    %
    %   2. Pressure-gradient-free closure:
    %          G = 0
    %
    %   The benchmark also verifies:
    %
    %   - the gas traction-jump identity;
    %   - equality of the two gas tractions when G = 0;
    %   - consistency between the analytical flux expression and the
    %     reconstructed gas-velocity profile;
    %   - convergence of both thickness inversions.
    %
    % INPUT
    %   caseData.D_o            outer air-water diameter [m]
    %   caseData.U_o            measured rise velocity [m/s]
    %   caseData.T_C            temperature [degC]
    %   caseData.oilName        oil identifier
    %   caseData.rho_o          oil density override [kg/m^3]
    %   caseData.deltaRange     thickness-search interval [m]
    %
    % OUTPUT
    %   benchmark.tests         table containing all benchmark results
    %   benchmark.allPassed     true when every test passes
    %   benchmark.closedResult  zero-relative-flux result
    %   benchmark.openResult    zero-pressure-gradient result

    arguments
        caseData struct
    end

    %% 1. Initialise benchmark records

    records = struct( ...
                     'Test', {}, ...
                     'Pass', {}, ...
                     'Error', {}, ...
                     'Tolerance', {}, ...
                     'Detail', {});

    %% 2. Common model options

    baseOptions = struct();

    baseOptions.rho_o = caseData.rho_o;
    baseOptions.saveResult = false;
    baseOptions.errorIfNoRoot = false;

    baseOptions.deltaMin = caseData.deltaRange(1);
    baseOptions.deltaMax = caseData.deltaRange(2);
    baseOptions.nScan = 300;

    %% 3. Run the zero-relative-flux model

    closedOptions = baseOptions;
    closedOptions.gasClosure = 'closed-shell';

    closedResult = RA_ThreePhaseContinuumModel( ...
                                               caseData.D_o, ...
                                               caseData.U_o, ...
                                               caseData.T_C, ...
                                               caseData.oilName, ...
                                               closedOptions);

    %% 4. Run the pressure-gradient-free model

    openOptions = baseOptions;
    openOptions.gasClosure = 'zero-pressure-gradient';

    openResult = RA_ThreePhaseContinuumModel( ...
                                             caseData.D_o, ...
                                             caseData.U_o, ...
                                             caseData.T_C, ...
                                             caseData.oilName, ...
                                             openOptions);

    %% 5. Zero-relative-flux closure checks

    if closedResult.success

        state = closedResult.solution;

        % --------------------------------------------------------------
        % Check 1: zero relative gas flux
        % --------------------------------------------------------------

        fluxScale = max([ ...
                         abs(state.gas.M_C * state.DeltaA), ...
                         abs(state.gas.M_P * state.G_amplitude), ...
                         realmin]);

        zeroFluxError = ...
            abs(state.q_relative) / fluxScale;

        addTest( ...
                'ClosedShellZeroFlux', ...
                zeroFluxError, ...
                1e-9, ...
                'The zero-relative-flux closure satisfies q_relative = 0.');

        % --------------------------------------------------------------
        % Check 2: traction-jump identity
        %
        % tau_aw - tau_oa = delta_a*G
        % --------------------------------------------------------------

        tractionScale = max([ ...
                             abs(state.tau_aw_amplitude), ...
                             abs(state.tau_oa_amplitude), ...
                             abs(state.delta_a * state.G_amplitude), ...
                             realmin]);

        tractionJumpError = ...
            abs(state.tractionJumpCheck) / tractionScale;

        addTest( ...
                'ClosedShellTractionJump', ...
                tractionJumpError, ...
                1e-9, ...
                ['The gas tractions satisfy ', ...
                     'tau_aw - tau_oa = delta_a*G.']);

        % --------------------------------------------------------------
        % Check 3: reconstructed velocity-profile flux
        % --------------------------------------------------------------

        profile = RA_Continuum_ReconstructVelocityProfile( ...
                                                          closedResult, 401);

        % Important:
        % max(A,B) performs elementwise comparison if A is a vector.
        % Supplying all candidates in one vector ensures a scalar scale.
        profileFluxScale = max([ ...
                                abs(profile.qCouette_m2_s), ...
                                abs(profile.qPressure_m2_s), ...
                                abs(state.q_relative), ...
                                realmin]);

        profileFluxError = ...
            abs(profile.qTotal_m2_s - state.q_relative) / ...
            profileFluxScale;

        addTest( ...
                'ClosedShellProfileFlux', ...
                profileFluxError, ...
                1e-6, ...
                ['The integrated reconstructed velocity profile agrees ', ...
                     'with the analytical relative-flux expression.']);

    else

        addTest( ...
                'ClosedShellConvergence', ...
                Inf, ...
                0, ...
                'The zero-relative-flux inversion must converge.');

    end

    %% 6. Pressure-gradient-free closure checks

    if openResult.success

        state = openResult.solution;

        % --------------------------------------------------------------
        % Check 4: prescribed zero pressure gradient
        % --------------------------------------------------------------

        zeroGradientError = abs(state.G_amplitude);

        addTest( ...
                'OpenFilmZeroGradient', ...
                zeroGradientError, ...
                1e-14, ...
                'The pressure-gradient-free closure satisfies G = 0.');

        % --------------------------------------------------------------
        % Check 5: equal gas tractions when G = 0
        % --------------------------------------------------------------

        tractionScale = max([ ...
                             abs(state.tau_oa_amplitude), ...
                             abs(state.tau_aw_amplitude), ...
                             realmin]);

        equalTractionError = ...
            abs( ...
                state.tau_aw_amplitude - ...
                state.tau_oa_amplitude) / tractionScale;

        addTest( ...
                'OpenFilmEqualTraction', ...
                equalTractionError, ...
                1e-9, ...
                ['The pressure-gradient-free continuum gas film has ', ...
                     'equal tractions at its two boundaries.']);

        % --------------------------------------------------------------
        % Check 6: reconstructed velocity-profile flux
        % --------------------------------------------------------------

        profile = RA_Continuum_ReconstructVelocityProfile( ...
                                                          openResult, 401);

        profileFluxScale = max([ ...
                                abs(profile.qCouette_m2_s), ...
                                abs(profile.qPressure_m2_s), ...
                                abs(state.q_relative), ...
                                realmin]);

        profileFluxError = ...
            abs(profile.qTotal_m2_s - state.q_relative) / ...
            profileFluxScale;

        addTest( ...
                'OpenFilmProfileFlux', ...
                profileFluxError, ...
                1e-6, ...
                ['The integrated reconstructed velocity profile agrees ', ...
                     'with the analytical relative-flux expression.']);

    else

        addTest( ...
                'OpenFilmConvergence', ...
                Inf, ...
                0, ...
                'The pressure-gradient-free inversion must converge.');

    end

    %% 7. Root-stability check for the zero-relative-flux model

    coarseOptions = baseOptions;
    coarseOptions.gasClosure = 'closed-shell';
    coarseOptions.nScan = 250;

    refinedOptions = baseOptions;
    refinedOptions.gasClosure = 'closed-shell';
    refinedOptions.nScan = 600;

    coarseResult = RA_ThreePhaseContinuumModel( ...
                                               caseData.D_o, ...
                                               caseData.U_o, ...
                                               caseData.T_C, ...
                                               caseData.oilName, ...
                                               coarseOptions);

    refinedResult = RA_ThreePhaseContinuumModel( ...
                                                caseData.D_o, ...
                                                caseData.U_o, ...
                                                caseData.T_C, ...
                                                caseData.oilName, ...
                                                refinedOptions);

    if coarseResult.success && refinedResult.success

        rootStabilityError = ...
            abs( ...
                refinedResult.delta_a - ...
                coarseResult.delta_a) / ...
            coarseResult.delta_a;

    else

        rootStabilityError = Inf;

    end

    addTest( ...
            'ClosedShellRootStability', ...
            rootStabilityError, ...
            0.02, ...
            ['The zero-relative-flux thickness root is stable to ', ...
                 'residual-scan refinement.']);

    %% 8. Root-stability check for the pressure-gradient-free model

    coarseOptions.gasClosure = 'zero-pressure-gradient';
    refinedOptions.gasClosure = 'zero-pressure-gradient';

    coarseOpenResult = RA_ThreePhaseContinuumModel( ...
                                                   caseData.D_o, ...
                                                   caseData.U_o, ...
                                                   caseData.T_C, ...
                                                   caseData.oilName, ...
                                                   coarseOptions);

    refinedOpenResult = RA_ThreePhaseContinuumModel( ...
                                                    caseData.D_o, ...
                                                    caseData.U_o, ...
                                                    caseData.T_C, ...
                                                    caseData.oilName, ...
                                                    refinedOptions);

    if coarseOpenResult.success && refinedOpenResult.success

        rootStabilityError = ...
            abs( ...
                refinedOpenResult.delta_a - ...
                coarseOpenResult.delta_a) / ...
            coarseOpenResult.delta_a;

    else

        rootStabilityError = Inf;

    end

    addTest( ...
            'OpenFilmRootStability', ...
            rootStabilityError, ...
            0.02, ...
            ['The pressure-gradient-free thickness root is stable to ', ...
                 'residual-scan refinement.']);

    %% 9. Assemble benchmark output

    benchmark = struct();

    benchmark.tests = struct2table(records);
    benchmark.allPassed = all(benchmark.tests.Pass);

    benchmark.closedResult = closedResult;
    benchmark.openResult = openResult;

    benchmark.closedRootStability = struct( ...
                                           'coarse', coarseResult, ...
                                           'refined', refinedResult);

    benchmark.openRootStability = struct( ...
                                         'coarse', coarseOpenResult, ...
                                         'refined', refinedOpenResult);

    %% 10. Display results

    fprintf('\n');
    fprintf('THREE-PHASE CONTINUUM BENCHMARKS\n');
    fprintf('================================\n');

    disp(benchmark.tests(:, { ...
                            'Test', ...
                            'Pass', ...
                            'Error', ...
                            'Tolerance'}));

    if benchmark.allPassed

        fprintf('ALL CONTINUUM BENCHMARKS PASSED.\n');

    else

        fprintf([ ...
                 'ONE OR MORE CONTINUUM BENCHMARKS FAILED. ', ...
                 'Inspect benchmark.tests.\n']);

    end

    %% Local helper: add one benchmark record

    function addTest(name, errorValue, tolerance, detail)

        item = struct();

        item.Test = string(name);

        item.Pass = ...
            isfinite(errorValue) && ...
            errorValue <= tolerance;

        item.Error = errorValue;
        item.Tolerance = tolerance;
        item.Detail = string(detail);

        records(end + 1) = item;

    end

end
