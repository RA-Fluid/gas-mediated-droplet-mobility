function RA_BGK_ValidateOptions(options, D_o)
    % Fail early for unsupported or inconsistent settings.

    assert(options.deltaMin > 0, 'deltaMin must be positive.');
    assert(options.deltaMax > options.deltaMin, 'deltaMax must exceed deltaMin.');
    assert(options.deltaMax < 0.5 * D_o, 'deltaMax must leave a positive oil core.');
    assert(options.nScan >= 20, 'Use at least 20 residual scan points.');
    assert(any(strcmpi(options.buoyancyModel, {'full', 'oil-only'})), ...
           'buoyancyModel must be full or oil-only.');
    assert(any(strcmpi(options.gasClosure, ...
                       {'closed-shell', 'zero-pressure-gradient'})), ...
           'gasClosure must be closed-shell or zero-pressure-gradient.');
    assert(options.kinetic.nVelocity >= 12 && mod(options.kinetic.nVelocity, 2) == 0, ...
           'nVelocity must be an even integer of at least 12.');
    assert(options.kinetic.nSpace >= 21, 'nSpace must be at least 21.');
    assert(abs(options.kinetic.alpha_oa - 1) < 1e-14 && ...
           abs(options.kinetic.alpha_aw - 1) < 1e-14, ...
           ['The validated direct BGK boundary operator currently supports ', ...
            'fully diffuse interfaces only.']);
end
