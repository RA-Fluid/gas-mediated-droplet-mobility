function response = RA_BGK_InterpolateResponse(tab, Kn, h, fixed, kopts)
    % RA_BGK_INTERPOLATERESPONSE Interpolate and dimensionalise the L-BGK operator.
    valid = tab.converged & isfinite(tab.qS) & ...
        isfinite(tab.tau0S) & isfinite(tab.tau1S);
    assert(nnz(valid) >= 4, 'Fewer than four converged BGK table rows.');
    x = log(tab.Kn(valid));
    xq = log(Kn);
    if ~kopts.extrapolate && (xq < min(x) || xq > max(x))
        error('Kn %.4g is outside table [%.4g, %.4g].', ...
              Kn, min(tab.Kn(valid)), max(tab.Kn(valid)));
    end
    F = @(v)interp1(x, v(valid), xq, kopts.interpolation, 'extrap');
    qU0 = h * F(tab.qU0) - h; % flux relative to oil interface
    qU1 = h * F(tab.qU1);
    qS = h * F(tab.qS);
    sourceToG = -2 * fixed.lambda_mfp^2 / (pi * fixed.mu_a);
    tScale = fixed.mu_a / h;
    response = struct('Kn', Kn, 'qU0', qU0, 'qU1', qU1, 'qG', qS * sourceToG, ...
                      'tau0U0', tScale * F(tab.tau0U0), 'tau0U1', tScale * F(tab.tau0U1), ...
                      'tau1U0', tScale * F(tab.tau1U0), 'tau1U1', tScale * F(tab.tau1U1), ...
                      'tau0G', tScale * F(tab.tau0S) * sourceToG, ...
                      'tau1G', tScale * F(tab.tau1S) * sourceToG, ...
                      'converged', true, 'tableRange', [min(tab.Kn(valid)), max(tab.Kn(valid))], ...
                      'sourceToPressureGradient', sourceToG);
end
