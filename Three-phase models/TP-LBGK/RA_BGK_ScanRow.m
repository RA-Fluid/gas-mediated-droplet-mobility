function row = RA_BGK_ScanRow(state)
    % RA_BGK_SCANROW Compact output used during residual bracketing.
    fields = {'delta_a', 'R_0', 'Kn', 'A_o', 'A_w', 'G_amplitude', ...
              'q_relative_check', 'meanRelativeGasVelocity', 'throughflowTimescale', ...
              'tau_oa_amplitude', 'tau_aw_amplitude', 'f_eq', 'beta_eq', 'b_eq', ...
              'cD_Feng', 'cD_observed', 'FD_Feng', 'FB_selected', 'residual', ...
              'relativeResidual', 'matrixConditionNumber', 'valid', 'message'};
    row = struct();
    for k = 1:numel(fields)
        row.(fields{k}) = state.(fields{k});
    end
end
